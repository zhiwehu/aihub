#!/bin/bash
# Run the AIHub model tier natively on this Mac and hand its URLs to the
# containerised control plane.
#
#   ./model-host.sh start    # aihub-models serve (:8790) + asr/llm/tts workers
#   ./model-host.sh status
#   ./model-host.sh stop
#
# MLX only runs on macOS, so these processes stay on the host. They bind
# 127.0.0.1; Docker Desktop's host.docker.internal proxies to host loopback, so
# no rebinding is needed (verified with `docker run busybox wget`).
set -eu

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
PY="$ROOT/.venv/bin/python"
DATA="${AIHUB_DATA:-$ROOT/data}"
ENVDIR="$HERE/env"
ENVFILE="$ENVDIR/models.env"
PIDS="$ENVDIR/pids"

ASR_PORT=8781
LLM_PORT=8782
TTS_PORT=8767
MEDIA_PORT=8790

say() { printf '%s\n' "$*"; }
die() { printf '错误: %s\n' "$*" >&2; exit 1; }

[ -x "$PY" ] || die "找不到 $PY"
[ -f "$DATA/settings.json" ] || die "找不到 $DATA/settings.json（先跑一次 ./start.sh 生成配置）"

model_of() {  # $1 = asr|llm|tts
  "$PY" - "$DATA/settings.json" "$1" <<'PY'
import json, sys
print(json.load(open(sys.argv[1]))[sys.argv[2]]['model'])
PY
}

gen_token() { "$PY" -c 'import secrets;print(secrets.token_urlsafe(32))'; }
gen_id()    { "$PY" -c 'import secrets;print(secrets.token_hex(16))'; }

write_env() {
  mkdir -p "$ENVDIR"
  [ -f "$ENVFILE" ] && return 0
  ( umask 077
    cat > "$ENVFILE" <<EOF
# Generated by model-host.sh — bearer tokens shared with the container.
# Consumed by compose.yaml via env_file. chmod 600, never commit.
VOICE_ASR_KEY=$(gen_token)
VOICE_LLM_KEY=$(gen_token)
VOICE_TTS_KEY=$(gen_token)
AIHUB_MODELS_TOKEN=$(gen_token)
# Container-side address of the native post-processing service.
AIHUB_MODELS_URL=http://host.docker.internal:$MEDIA_PORT
EOF
  )
  say "已生成 $ENVFILE"
}

token_of() { sed -n "s/^$1=//p" "$ENVFILE"; }   # $1 = full env var name

port_busy() { [ -n "$(lsof -nP -iTCP:"$1" -sTCP:LISTEN -t 2>/dev/null | head -1)" ]; }

wait_health() {  # $1 = port, $2 = bearer token
  for _ in $(seq 1 90); do
    code=$(curl -s -o /dev/null -w '%{http_code}' -m 2 \
      -H "Authorization: Bearer $2" "http://127.0.0.1:$1/health" 2>/dev/null || true)
    [ "$code" = "200" ] && return 0
    sleep 1
  done
  return 1
}

start_one() {  # $1 = label, $2 = port, rest = command
  label="$1"; port="$2"; shift 2
  if port_busy "$port"; then
    say "  $label: 端口 $port 已被占用，跳过"
    return 0
  fi
  nohup "$@" >"$ENVDIR/$label.log" 2>&1 &
  echo $! > "$PIDS/$label.pid"
  say "  $label: 启动中 pid $(cat "$PIDS/$label.pid")  :$port"
}

report_health() {  # $1 = label, $2 = port, $3 = token
  if wait_health "$2" "$3"; then say "  $1 就绪"
  else say "  $1 未就绪 — 看 $ENVDIR/$1.log"; fi
}

do_start() {
  write_env
  mkdir -p "$PIDS"

  asr_model="$(model_of asr)"
  llm_model="$(model_of llm)"
  tts_model="$(model_of tts)"
  say "模型（来自 $DATA/settings.json）:"
  say "  asr = $asr_model"
  say "  llm = $llm_model"
  say "  tts = $tts_model"
  say
  say "启动模型 tier…"

  start_one asr "$ASR_PORT" env AIHUB_WORKER_TOKEN="$(token_of VOICE_ASR_KEY)" \
    "$PY" -m aihub_models worker --kind asr --model "$asr_model" \
    --service-id "$(gen_id)" --port "$ASR_PORT"
  start_one llm "$LLM_PORT" env AIHUB_WORKER_TOKEN="$(token_of VOICE_LLM_KEY)" \
    "$PY" -m aihub_models worker --kind llm --model "$llm_model" \
    --service-id "$(gen_id)" --port "$LLM_PORT"
  start_one tts "$TTS_PORT" env AIHUB_WORKER_TOKEN="$(token_of VOICE_TTS_KEY)" \
    "$PY" -m aihub_models worker --kind tts --model "$tts_model" \
    --service-id "$(gen_id)" --port "$TTS_PORT"
  # The container reaches this service via host.docker.internal, so its peer is
  # the bridge gateway; AIHUB_MODELS_ALLOW_REMOTE lifts the loopback-only check
  # (the bearer token still gates every request).
  start_one media "$MEDIA_PORT" env AIHUB_MODELS_ALLOW_REMOTE=1 \
    "$PY" -m aihub_models serve --data "$DATA" --port "$MEDIA_PORT" \
    --token "$(token_of AIHUB_MODELS_TOKEN)"

  say
  say "等待模型就绪（首次加载 LLM 可能要一两分钟）…"
  report_health asr "$ASR_PORT" "$(token_of VOICE_ASR_KEY)"
  report_health llm "$LLM_PORT" "$(token_of VOICE_LLM_KEY)"
  report_health tts "$TTS_PORT" "$(token_of VOICE_TTS_KEY)"
  report_health media "$MEDIA_PORT" "$(token_of AIHUB_MODELS_TOKEN)"

  say
  say "模型 tier URL（容器内走 host.docker.internal）:"
  say "  asr   http://host.docker.internal:$ASR_PORT/v1/audio/transcriptions"
  say "  llm   http://host.docker.internal:$LLM_PORT/v1/chat/completions"
  say "  tts   http://host.docker.internal:$TTS_PORT/v1/audio/speech"
  say "  media http://host.docker.internal:$MEDIA_PORT"
  say
  say "下一步: ./configure.sh  然后  docker compose up -d --build"
}

do_stop() {
  say "停止模型 tier…"
  for label in asr llm tts media; do
    pidfile="$PIDS/$label.pid"
    [ -f "$pidfile" ] || continue
    pid="$(cat "$pidfile")"
    kill -0 "$pid" 2>/dev/null && { kill "$pid" 2>/dev/null || true; say "  已停止 $label (pid $pid)"; }
    rm -f "$pidfile"
  done
  for port in "$ASR_PORT" "$LLM_PORT" "$TTS_PORT" "$MEDIA_PORT"; do
    pid=$(lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null | head -1 || true)
    [ -n "$pid" ] && { kill "$pid" 2>/dev/null || true; say "  回收端口 $port (pid $pid)"; }
  done
  say "完成。"
}

do_status() {
  for pair in "asr:$ASR_PORT" "llm:$LLM_PORT" "tts:$TTS_PORT" "media:$MEDIA_PORT"; do
    label="${pair%%:*}"; port="${pair##*:}"
    pid=$(lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null | head -1 || true)
    if [ -n "$pid" ]; then say "  $label 运行中 pid $pid  :$port"
    else say "  $label 未运行"; fi
  done
}

case "${1:-start}" in
  start)  do_start ;;
  stop)   do_stop ;;
  status) do_status ;;
  *) die "用法: $0 [start|stop|status]" ;;
esac
